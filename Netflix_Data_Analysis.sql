/* ============================================================
   NETFLIX DATA ANALYSIS PROJECT
   Database : netflix_db
   Table    : dbo.netflix_customers
   ============================================================ */


/* ============================================================
   QUESTION 1
   What is the total number of customers?
   ============================================================ */

SELECT 
    COUNT(*) AS [Total Customer]
FROM dbo.netflix_customers;
GO


/* ============================================================
   QUESTION 2
   How many customers are currently active?
   ============================================================ */

SELECT 
    COUNT(*) AS [Active Customer]
FROM dbo.netflix_customers
WHERE Account_Status = 'Active';
GO


/* ============================================================
   QUESTION 3
   How many customers are there for each subscription plan?
   ============================================================ */

SELECT 
    Subscription_Plan,
    COUNT(*) AS [Customer]
FROM dbo.netflix_customers
GROUP BY Subscription_Plan
ORDER BY [Customer] DESC;
GO


/* ============================================================
   QUESTION 4
   What is the revenue generated by each subscription plan?
   ============================================================ */

SELECT 
    Subscription_Plan,
    SUM(Customer_Revenue) AS [Total Revenue]
FROM dbo.netflix_customers
GROUP BY Subscription_Plan
ORDER BY [Total Revenue] DESC;
GO


/* ============================================================
   QUESTION 5
   Which genres are the most popular based on number of views?
   ============================================================ */

SELECT 
    Genre,
    COUNT(*) AS [Views]
FROM dbo.netflix_customers
GROUP BY Genre
ORDER BY [Views] DESC;
GO


/* ============================================================
   QUESTION 6
   How many views are there from each country?
   ============================================================ */

SELECT 
    Country,
    COUNT(*) AS [Views]
FROM dbo.netflix_customers
GROUP BY Country
ORDER BY [Views] DESC;
GO


/* ============================================================
   QUESTION 7
   How many customers use each device?
   ============================================================ */

SELECT 
    Device,
    COUNT(*) AS [Device Uses]
FROM dbo.netflix_customers
GROUP BY Device
ORDER BY [Device Uses] DESC;
GO


/* ============================================================
   QUESTION 8
   What is the average watch time in hours for each
   subscription plan?
   Round the average to 2 decimal places.
   ============================================================ */

SELECT 
    Subscription_Plan,
    ROUND(AVG(Watch_Hours), 2) AS [Avg Watch Hours]
FROM dbo.netflix_customers
GROUP BY Subscription_Plan
ORDER BY [Avg Watch Hours] DESC;
GO


/* ============================================================
   QUESTION 9
   Who are the top 10 customers based on revenue?
   ============================================================ */

SELECT TOP 10
    Customer_Name,
    Customer_Revenue AS [Revenue]
FROM dbo.netflix_customers
ORDER BY Customer_Revenue DESC;
GO


/* ============================================================
   QUESTION 10
   Compare Movies vs TV Shows based on watch hours.
   ============================================================ */

SELECT 
    Content_Type,
    SUM(Watch_Hours) AS [Total Watch Hours]
FROM dbo.netflix_customers
GROUP BY Content_Type
ORDER BY [Total Watch Hours] DESC;
GO


/* ============================================================
   QUESTION 11
   What is the average rating for each genre?
   Round the average rating to 2 decimal places.
   ============================================================ */

SELECT 
    Genre,
    ROUND(AVG(Avg_Rating), 2) AS [Avg Rating]
FROM dbo.netflix_customers
GROUP BY Genre
ORDER BY [Avg Rating] DESC;
GO


/* ============================================================
   QUESTION 12
   How many customers are there for each account status?
   ============================================================ */

SELECT 
    Account_Status,
    COUNT(*) AS [Customer Count]
FROM dbo.netflix_customers
GROUP BY Account_Status
ORDER BY [Customer Count] DESC;
GO